import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const read=name=>readFileSync(new URL(name,import.meta.url),'utf8');
const sha=text=>createHash('sha256').update(text).digest('hex');
const manifest=JSON.parse(read('package.json'));
const inputs=['contract.mjs','client-entry.mjs'];
const contract=read(inputs[0]).replace(/^export /gm,'');
const entry=read(inputs[1]).replace(/^import .*?;\r?\n/,'').replace(/^export /gm,'');
const output=`// Generated by build.mjs; no network bundler or embedded runtime.\nwindow.__ModuleLoader__.load({id:${JSON.stringify(manifest.name)},factory:(require)=>{\n${contract}\n${entry}\nreturn {inject,apply};\n}});\n`;
new Function(output);
const info=JSON.stringify({format:1,package:manifest.name,version:manifest.version,inputs:Object.fromEntries(inputs.map(name=>[name,sha(read(name))])),clientSha256:sha(output)},null,2)+'\n';
if(process.argv.includes('--check')){
 assert.equal(read('lib/client.js'),output,'Stale client bundle; run node build.mjs');
 assert.equal(read('lib/build-info.json'),info,'Stale build provenance');
}else{
 mkdirSync(new URL('lib/',import.meta.url),{recursive:true});
 writeFileSync(new URL('lib/client.js',import.meta.url),output);
 writeFileSync(new URL('lib/build-info.json',import.meta.url),info);
}
console.log(JSON.stringify({status:'PASS',checked:process.argv.includes('--check'),package:manifest.name,version:manifest.version,bytes:Buffer.byteLength(output),sha256:sha(output)}));
